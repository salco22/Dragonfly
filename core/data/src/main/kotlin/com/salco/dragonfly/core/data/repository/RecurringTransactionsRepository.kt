import com.salco.dragonfly.core.database.DatabaseTransactionRunner
import com.salco.dragonfly.core.database.dao.RecurringTransactionDao
import com.salco.dragonfly.core.database.model.PopulatedRecurringTransaction
import com.salco.dragonfly.core.database.model.RecurringTransactionEntity
import com.salco.dragonfly.core.model.AccountRef
import com.salco.dragonfly.core.model.AccountType
import com.salco.dragonfly.core.model.RecurrenceRule
import com.salco.dragonfly.core.model.RecurringTransaction
import com.salco.dragonfly.core.model.TransactionDraft
import com.salco.dragonfly.core.model.TransactionType
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.map
import java.time.LocalDate
import javax.inject.Inject

interface RecurringTransactionsRepository {
    fun observeRecurringTransactions(): Flow<List<RecurringTransaction>>
    fun observeRecurringTransaction(id: Long): Flow<RecurringTransaction?>

    /**
     * Saves [recurring] and returns its id. When an existing schedule changes, dates already
     * generated are not generated again.
     */
    suspend fun saveRecurringTransaction(recurring: RecurringTransaction): Long

    /** Deletes the schedule; transactions it already created stay. */
    suspend fun deleteRecurringTransaction(id: Long)

    /** Creates every transaction due on or before [today] and returns them, oldest first per schedule. */
    suspend fun generateDueTransactions(today: LocalDate): List<TransactionDraft>
}

internal class OfflineRecurringTransactionsRepository @Inject constructor(
    private val recurringDao: RecurringTransactionDao,
    private val transactionsRepository: TransactionsRepository,
    private val runInTransaction: DatabaseTransactionRunner,
) : RecurringTransactionsRepository {

    override fun observeRecurringTransactions(): Flow<List<RecurringTransaction>> =
        recurringDao.observeAll().map { list -> list.map { it.asExternalModel() } }

    override fun observeRecurringTransaction(id: Long): Flow<RecurringTransaction?> =
        recurringDao.observeById(id).map { it?.asExternalModel() }

    override suspend fun saveRecurringTransaction(recurring: RecurringTransaction): Long = runInTransaction {
        val previous = recurring.id.takeIf { it != 0L }?.let { recurringDao.getById(it) }
        val created = if (previous == null) 0 else occurrencesAlreadyCovered(previous.rule(), previous.occurrencesCreated, recurring.rule)
        val entity = recurring.asEntity(occurrencesCreated = created)
        val rowId = recurringDao.upsert(entity)
        if (recurring.id != 0L) recurring.id else rowId
    }

    override suspend fun deleteRecurringTransaction(id: Long) = recurringDao.deleteById(id)

    override suspend fun generateDueTransactions(today: LocalDate): List<TransactionDraft> {
        val created = mutableListOf<TransactionDraft>()
        recurringDao.getDue(today.toEpochDay()).forEach { due ->
            // One database transaction per schedule: its transactions and counter move together.
            created += runInTransaction {
                var recurring = recurringDao.getById(due.id) ?: return@runInTransaction emptyList()
                val drafts = mutableListOf<TransactionDraft>()
                while (recurring.active && recurring.nextDate != null && recurring.nextDate!! <= today.toEpochDay()) {
                    val draft = recurring.draftFor(LocalDate.ofEpochDay(recurring.nextDate!!))
                    transactionsRepository.saveTransaction(draft)
                    drafts += draft
                    val occurrences = recurring.occurrencesCreated + 1
                    recurring = recurring.copy(
                        occurrencesCreated = occurrences,
                        nextDate = recurring.rule().nextAfter(occurrences)?.toEpochDay(),
                    )
                }
                recurringDao.upsert(recurring)
                drafts
            }
        }
        return created
    }

    /**
     * How many occurrences of [newRule] fall on or before the last date generated by [oldRule],
     * so editing a schedule never repeats a date that already has its transaction.
     */
    private fun occurrencesAlreadyCovered(oldRule: RecurrenceRule, oldCreated: Int, newRule: RecurrenceRule): Int {
        if (oldCreated == 0) return 0
        val lastGenerated = oldRule.occurrence(oldCreated - 1)
        var index = 0
        while (!newRule.occurrence(index).isAfter(lastGenerated)) index++
        return index
    }
}

private fun RecurringTransactionEntity.rule() = RecurrenceRule(
    frequency = frequency,
    interval = interval,
    startDate = LocalDate.ofEpochDay(startDate),
    endDate = endDate?.let(LocalDate::ofEpochDay),
    maxOccurrences = maxOccurrences,
)

private fun RecurringTransactionEntity.ref(accountId: Long?, name: String?, counterpartyType: AccountType): AccountRef =
    accountId?.let { AccountRef.Existing(it) } ?: AccountRef.New(name.orEmpty(), counterpartyType, currencyCode)

private fun RecurringTransactionEntity.draftFor(date: LocalDate) = TransactionDraft(
    type = type,
    description = description,
    date = date,
    amount = amount,
    currencyCode = currencyCode,
    foreignAmount = foreignAmount,
    source = ref(sourceAccountId, sourceName, AccountType.REVENUE),
    destination = ref(destinationAccountId, destinationName, AccountType.EXPENSE),
    notes = notes,
    categoryName = categoryName,
    tagNames = tagNames.split('\n').filter { it.isNotBlank() },
    budgetId = budgetId,
    billId = billId,
)

private fun PopulatedRecurringTransaction.asExternalModel(): RecurringTransaction {
    val r = recurring
    return RecurringTransaction(
        id = r.id,
        template = r.draftFor(LocalDate.ofEpochDay(r.startDate)),
        rule = r.rule(),
        occurrencesCreated = r.occurrencesCreated,
        nextDate = r.nextDate?.let(LocalDate::ofEpochDay),
        active = r.active,
        sourceName = resolvedSourceName.orEmpty(),
        destinationName = resolvedDestinationName.orEmpty(),
    )
}

private fun RecurringTransaction.asEntity(occurrencesCreated: Int): RecurringTransactionEntity {
    val source = template.source
    val destination = template.destination
    return RecurringTransactionEntity(
        id = id,
        type = template.type,
        description = template.description,
        amount = template.amount,
        currencyCode = template.currencyCode,
        foreignAmount = template.foreignAmount,
        sourceAccountId = (source as? AccountRef.Existing)?.id,
        sourceName = (source as? AccountRef.New)?.name?.trim(),
        destinationAccountId = (destination as? AccountRef.Existing)?.id,
        destinationName = (destination as? AccountRef.New)?.name?.trim(),
        notes = template.notes,
        categoryName = template.categoryName,
        tagNames = template.tagNames.joinToString("\n"),
        budgetId = template.budgetId.takeIf { template.type == TransactionType.WITHDRAWAL },
        billId = template.billId.takeIf { template.type == TransactionType.WITHDRAWAL },
        frequency = rule.frequency,
        interval = rule.interval,
        startDate = rule.startDate.toEpochDay(),
        endDate = rule.endDate?.toEpochDay(),
        maxOccurrences = rule.maxOccurrences,
        occurrencesCreated = occurrencesCreated,
        nextDate = rule.nextAfter(occurrencesCreated)?.toEpochDay(),
        active = active,
    )
}
